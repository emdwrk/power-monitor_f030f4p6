const fglyph_t *myfont_find(uint32_t unicode)
{
    uint8_t i;
    static fglyph_t g;
    for (i = 0; i < 52; i++)
    {
        if (uni_tab[i] == unicode && gtab[i].w)
        {
            g.unicode = unicode;
            g.bm  = gtab[i].bm;
            g.w   = gtab[i].w;
            g.h   = gtab[i].h;
            g.ox  = gtab[i].ox;
            g.oy  = gtab[i].oy;
            return &g;
        }
    }
    return 0;
}

int myfont_pixel(const fglyph_t *g, int gx, int gy)
{
    uint32_t bit = (uint32_t)g->bm + (uint32_t)(gy * g->w + gx);
    return (font_bits[bit >> 3] >> (7 - (bit & 7))) & 1;
}